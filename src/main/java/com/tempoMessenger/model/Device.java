package com.tempoMessenger.model;

public class Device {

	private String name;
	private long lastseen;
	
	public String getName() {
		return name;
	}
	public void setName(String name) {
		this.name = name;
	}
	public long getLastseen() {
		return lastseen;
	}
	public void setLastseen(long lastseen) {
		this.lastseen = lastseen;
	}
	
}
